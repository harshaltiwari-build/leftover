package app.leftover.ui

/** Every destination in the app. Routes with ids carry them as a path argument. */
object Routes {
    const val LAUNCH = "launch"

    const val ONB_FIRST = "onboarding/first"
    const val ONB_RHYTHM = "onboarding/rhythm"
    const val ONB_BALANCE = "onboarding/balance"
    const val ONB_DONE = "onboarding/done"

    const val HOME = "home"
    const val LEFT = "home/left"
    const val ADD = "add"
    const val ADD_PATTERN = "add?kind={kind}&draft={draft}"
    fun add(kind: String) = "add?kind=$kind"

    /** Quick add filled in from the screenshot draft the view model is holding. */
    fun addDraft(income: Boolean) = "add?kind=${if (income) "Income" else "Expense"}&draft=true"
    const val VOICE = "voice"
    const val AFFORD = "afford"

    const val ACTIVITY = "activity"
    const val TX = "activity/tx/{id}"
    fun tx(id: Long) = "activity/tx/$id"
    const val ACCOUNTS = "accounts"
    const val ADD_ACCOUNT = "accounts/add?type={type}"
    fun addAccount(type: String? = null) = if (type == null) "accounts/add" else "accounts/add?type=$type"
    const val CASH = "accounts/cash/{id}"
    fun cash(id: Long) = "accounts/cash/$id"
    const val CARD = "accounts/card/{id}"
    fun card(id: Long) = "accounts/card/$id"

    const val PLAN = "plan"
    const val EDIT_LIMITS = "plan/limits"
    const val CATEGORIES = "plan/categories"
    const val GOALS = "plan/goals"
    const val GOAL = "plan/goals/{id}"
    fun goal(id: Long) = "plan/goals/$id"
    const val ADD_GOAL = "plan/goals/add"
    const val BILLS = "plan/bills"
    const val ADD_BILL = "plan/bills/add"
    const val WISHLIST = "plan/wishlist"
    const val CHECKIN = "plan/checkin"
    const val TAGS = "plan/tags"
    const val TAG = "plan/tags/{id}"
    fun tag(id: Long) = "plan/tags/$id"
    const val ADD_EMI = "plan/emi/add"
    const val EMI = "plan/emi/{id}"
    fun emi(id: Long) = "plan/emi/$id"

    const val SPLIT = "split"
    const val ADD_PERSON = "split/person/add"
    const val PERSON = "split/person/{id}"
    fun person(id: Long) = "split/person/$id"
    const val SPLIT_BILL = "split/bill?person={person}&group={group}"
    fun splitBill(personId: Long? = null, groupId: Long? = null) = "split/bill?person=${personId ?: -1}&group=${groupId ?: -1}"
    const val SETTLE = "split/settle/{id}?group={group}&amount={amount}"
    fun settle(personId: Long, groupId: Long? = null, amount: Long? = null) = "split/settle/$personId?group=${groupId ?: -1}&amount=${amount ?: -1}"
    const val ADD_GROUP = "split/group/add"
    const val GROUP = "split/group/{id}"
    fun group(id: Long) = "split/group/$id"

    const val INSIGHTS = "insights"
    const val RECAP = "insights/recap"
    const val REPORTS = "insights/reports"
    const val ASK = "insights/ask"
    const val SETTINGS = "settings"
    const val SMS = "settings/sms"
    const val REMINDERS = "settings/reminders"
    const val RHYTHM = "settings/rhythm"
    const val APPEARANCE = "settings/appearance"
    const val PRIVACY = "settings/privacy"
    const val ABOUT = "settings/about"
    const val DELETE = "settings/delete"
    const val BACKUP = "settings/backup"
    const val IMPORT_CSV = "settings/backup/import"
    const val REVIEW = "review"
    const val MANDATES = "settings/sms/mandates"
    const val RULES = "settings/sms/rules"

    val withBottomBar = setOf(HOME, ACTIVITY, PLAN, GOALS, BILLS, WISHLIST, SPLIT)
}
